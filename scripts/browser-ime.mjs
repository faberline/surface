import { mkdir, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
import { startWebServer } from './web-test-support.mjs';
const { chromium } = await import(process.env.SURFACE_PLAYWRIGHT || 'playwright');
const browser = await chromium.launch({headless:true,...(process.env.SURFACE_CHROME?{executablePath:process.env.SURFACE_CHROME}:{}),args:['--enable-unsafe-webgpu']});
const web = await startWebServer();
try {
  const page=await browser.newPage({viewport:{width:1000,height:900},deviceScaleFactor:2});
  const errors=[];page.on('pageerror',e=>errors.push(String(e)));page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
  await page.goto(web.url);
  await page.waitForFunction(()=>window.showcase&&document.querySelector('#status').textContent.startsWith('Ready'));
  const bounds=await page.evaluate(()=>Array.from(window.showcase.control_bounds('name')));
  const canvas=await page.locator('canvas').boundingBox();
  await page.mouse.click(canvas.x+bounds[0]+24,canvas.y+bounds[1]+24);
  await page.waitForFunction(()=>document.activeElement?.id==='surface-text-input');
  await page.evaluate(()=>{
    window.imeEvents=[];
    for(const type of ['compositionstart','compositionupdate','compositionend','beforeinput','input'])
      document.querySelector('#surface-text-input').addEventListener(type,e=>window.imeEvents.push({type,data:e.data,inputType:e.inputType,isComposing:e.isComposing}));
  });
  const session=await page.context().newCDPSession(page);
  const compose=(text,selectionStart=text.length,selectionEnd=selectionStart)=>session.send('Input.imeSetComposition',{text,selectionStart,selectionEnd});
  const commit=text=>session.send('Input.insertText',{text});
  const waitValue=value=>page.waitForFunction(value=>window.showcase.editing_state()[0]===value,value);
  await compose('ㄓㄨㄥ');
  await page.waitForFunction(()=>window.showcase.editing_state()[1]==='ㄓㄨㄥ'&&window.showcase.editing_state()[4]==='true');
  assert.equal(await page.evaluate(()=>window.showcase.editing_state()[0]),'');
  await compose('中文');
  await page.waitForFunction(()=>window.showcase.editing_state()[1]==='中文');
  await mkdir('artifacts',{recursive:true});
  await page.screenshot({path:'artifacts/browser-ime-preedit.png'});
  const candidate=await page.evaluate(()=>{
    const area=document.querySelector('#surface-text-input').getBoundingClientRect();
    const canvas=document.querySelector('canvas').getBoundingClientRect();
    const caret=Array.from(window.showcase.input_caret());
    return {left:area.left-canvas.left,top:area.top-canvas.top,caret};
  });
  assert.equal(candidate.caret.length,4);
  assert.ok(Math.abs(candidate.left-candidate.caret[0])<=1);
  assert.ok(Math.abs(candidate.top-candidate.caret[1])<=1);
  await commit('中文');await waitValue('中文');
  await page.waitForFunction(()=>window.showcase.editing_state()[4]==='false');
  await page.locator('#surface-text-input').evaluate(area=>{area.setSelectionRange(0,1);});
  await page.waitForFunction(()=>window.showcase.editing_state()[2]==='0'&&window.showcase.editing_state()[3]==='3');
  await compose('台');await commit('台');await waitValue('台文');
  await compose('ㄅㄆ');
  await page.waitForFunction(()=>window.showcase.editing_state()[4]==='true');
  await compose('',0,0);
  await page.waitForFunction(()=>window.showcase.editing_state()[4]==='false');
  await waitValue('台文');
  await page.keyboard.press(process.platform==='darwin'?'Meta+A':'Control+A');
  await commit('中👨‍👩‍👧‍👦e\u0301');await waitValue('中👨‍👩‍👧‍👦e\u0301');
  await page.keyboard.press('Backspace');await waitValue('中👨‍👩‍👧‍👦');
  await page.keyboard.press('Backspace');await waitValue('中');
  await page.keyboard.press(process.platform==='darwin'?'Meta+Z':'Control+Z');await waitValue('中👨‍👩‍👧‍👦');
  await page.keyboard.press(process.platform==='darwin'?'Meta+Shift+Z':'Control+Shift+Z');await waitValue('中');
  await page.keyboard.press(process.platform==='darwin'?'Meta+A':'Control+A');
  await commit('繁體中文、简体中文');await waitValue('繁體中文、简体中文');
  await compose('ㄅ');
  await page.waitForFunction(()=>window.showcase.editing_state()[4]==='true');
  await page.waitForFunction(()=>window.showcase.control_bounds('increment').length===4);
  const increment=await page.evaluate(()=>Array.from(window.showcase.control_bounds('increment')));
  await page.mouse.click(canvas.x+increment[0]+24,canvas.y+increment[1]+24);
  await page.waitForFunction(()=>window.showcase.editing_state()[4]==='false');
  assert.equal(await page.evaluate(()=>window.showcase.editing_state()[0]),'繁體中文、简体中文');
  await page.waitForFunction(()=>window.showcase.control_bounds('name').length===4);
  await page.mouse.click(canvas.x+bounds[0]+24,canvas.y+bounds[1]+24);
  await page.waitForFunction(()=>document.activeElement?.id==='surface-text-input');
  await page.keyboard.press(process.platform==='darwin'?'Meta+A':'Control+A');
  await commit('繁體中文、简体中文');await waitValue('繁體中文、简体中文');
  await page.screenshot({path:'artifacts/browser-ime-committed.png'});
  const events=await page.evaluate(()=>window.imeEvents);
  for(const type of ['compositionstart','compositionupdate','compositionend','input'])assert.ok(events.some(e=>e.type===type),type);
  assert.deepEqual(errors,[]);
  const evidence={browser:await browser.version(),driver:'Chrome Input.imeSetComposition / Input.insertText',committed:await page.evaluate(()=>window.showcase.editing_state()[0]),candidate,events,errors};
  await writeFile('artifacts/browser-ime.json',JSON.stringify(evidence,null,2)+'\n');
  console.log(JSON.stringify({browser:evidence.browser,committed:evidence.committed,events:events.length,errors}));
}finally{await browser.close();await web.close();}
