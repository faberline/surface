import { mkdir, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
import { startWebServer } from './web-test-support.mjs';
const { chromium }=await import(process.env.SURFACE_PLAYWRIGHT||'playwright');
const browser=await chromium.launch({headless:true,...(process.env.SURFACE_CHROME?{executablePath:process.env.SURFACE_CHROME}:{}),args:['--enable-unsafe-webgpu']});
const web=await startWebServer('material-gallery');
try{
  const page=await browser.newPage({viewport:{width:1100,height:1100},deviceScaleFactor:2});
  const errors=[];page.on('pageerror',e=>errors.push(String(e)));page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
  await page.goto(web.url);
  await page.waitForFunction(()=>window.gallery&&document.querySelector('#status').textContent.startsWith('Ready'));
  const state=()=>page.evaluate(()=>JSON.parse(window.gallery.inspect()));
  const wait=(predicate)=>page.waitForFunction(predicate);
  async function point(id){
    await page.waitForFunction(id=>window.gallery.control_bounds(id).length===4,id);
    const b=await page.evaluate(id=>Array.from(window.gallery.control_bounds(id)),id);
    const canvas=await page.locator('canvas').boundingBox();
    return {x:canvas.x+b[0]+b[2]/2,y:canvas.y+b[1]+b[3]/2,b,canvas};
  }
  const click=async id=>{const p=await point(id);await page.mouse.click(p.x,p.y);};
  await click('radio-0');await page.keyboard.press('ArrowDown');await wait(()=>JSON.parse(window.gallery.inspect()).radio===1);
  await page.keyboard.press('ArrowDown');await wait(()=>JSON.parse(window.gallery.inspect()).radio===0);
  await click('segment-0');await page.keyboard.press('ArrowRight');
  await wait(()=>JSON.parse(window.gallery.inspect()).focused==='segment-1');
  assert.equal((await state()).segment,0,'manual group focus does not select');
  await page.keyboard.press('Space');await wait(()=>JSON.parse(window.gallery.inspect()).segment===1);
  await click('check');await wait(()=>JSON.parse(window.gallery.inspect()).check==='Checked');
  await click('enabled');await wait(()=>JSON.parse(window.gallery.inspect()).enabled);
  const volume=await point('volume');
  await page.mouse.click(volume.canvas.x+volume.b[0]+12+0.85*(volume.b[2]-24),volume.y);
  await wait(()=>JSON.parse(window.gallery.inspect()).volume===85);
  await page.keyboard.press('ArrowLeft');await wait(()=>JSON.parse(window.gallery.inspect()).volume===80);
  await page.keyboard.press('Home');await wait(()=>JSON.parse(window.gallery.inspect()).volume===0);
  await page.keyboard.press('End');await wait(()=>JSON.parse(window.gallery.inspect()).volume===100);
  await mkdir('artifacts',{recursive:true});
  await page.screenshot({path:'artifacts/material-selection-light.png'});
  await click('theme');await wait(()=>JSON.parse(window.gallery.inspect()).dark);
  await page.screenshot({path:'artifacts/material-selection-dark.png'});
  await click('section-1');await wait(()=>JSON.parse(window.gallery.inspect()).section===1);
  const filled=await point('filled');
  await page.mouse.move(filled.x,filled.y);await page.mouse.down();
  assert.equal((await state()).clicks,0,'press updates on release');
  await page.mouse.up();await wait(()=>JSON.parse(window.gallery.inspect()).clicks===1);
  await click('disabled-action');assert.equal((await state()).clicks,1);
  await click('filter');await wait(()=>JSON.parse(window.gallery.inspect()).filter);
  await click('input-chip-remove');await wait(()=>!JSON.parse(window.gallery.inspect()).input_chip);
  await page.screenshot({path:'artifacts/material-actions.png'});
  await click('section-2');await wait(()=>JSON.parse(window.gallery.inspect()).section===2);
  await click('open-dialog');await wait(()=>JSON.parse(window.gallery.inspect()).dialog);
  await wait(()=>document.activeElement?.id==='surface-text-input');
  await page.keyboard.press(process.platform==='darwin'?'Meta+A':'Control+A');
  const session=await page.context().newCDPSession(page);
  await session.send('Input.insertText',{text:'中文框架'});
  await wait(()=>JSON.parse(window.gallery.inspect()).draft==='中文框架');
  assert.equal((await state()).name,'Surface','dialog draft stays separate');
  await page.keyboard.press('Escape');
  await wait(()=>!JSON.parse(window.gallery.inspect()).dialog&&JSON.parse(window.gallery.inspect()).focused==='open-dialog');
  assert.equal((await state()).name,'Surface');
  await click('open-dialog');await wait(()=>JSON.parse(window.gallery.inspect()).dialog);
  await point('rename-dialog');
  await click('section-1');await wait(()=>!JSON.parse(window.gallery.inspect()).dialog);
  assert.equal((await state()).section,2,'outside dismiss must not activate a background tab');
  await click('open-dialog');await wait(()=>document.activeElement?.id==='surface-text-input');
  await page.keyboard.press(process.platform==='darwin'?'Meta+A':'Control+A');await session.send('Input.insertText',{text:'中文框架'});
  await wait(()=>JSON.parse(window.gallery.inspect()).draft==='中文框架');
  await page.keyboard.press('Tab');await wait(()=>JSON.parse(window.gallery.inspect()).focused==='dialog-cancel');
  await page.keyboard.press('Tab');await wait(()=>JSON.parse(window.gallery.inspect()).focused==='dialog-save');
  await page.keyboard.press('Tab');await wait(()=>JSON.parse(window.gallery.inspect()).focused==='dialog-name');
  await page.screenshot({path:'artifacts/material-dialog.png'});
  const domExport=await page.evaluate(()=>JSON.parse(window.gallery.export_dom()));
  assert.equal(domExport.text_inputs['dialog-name'].value,'中文框架');
  assert.equal(domExport.interaction.focused,'dialog-name');
  assert.ok(domExport.dom.nodes.some(n=>n.role==='Dialog'&&n.stable_id==='rename-dialog'));
  assert.equal(domExport.layout.nodes.length,domExport.dom.nodes.length);
  await writeFile('artifacts/material-dom-export.json',JSON.stringify(domExport,null,2)+'\n');
  await click('dialog-save');await wait(()=>JSON.parse(window.gallery.inspect()).name==='中文框架'&&!JSON.parse(window.gallery.inspect()).dialog);
  await click('open-menu');await wait(()=>JSON.parse(window.gallery.inspect()).focused==='menu-rename');
  await page.keyboard.press('ArrowDown');await wait(()=>JSON.parse(window.gallery.inspect()).focused==='menu-close');
  await page.keyboard.press('Escape');await wait(()=>!JSON.parse(window.gallery.inspect()).menu&&JSON.parse(window.gallery.inspect()).focused==='open-menu');
  await page.setViewportSize({width:480,height:760});
  await click('open-dialog');await wait(()=>JSON.parse(window.gallery.inspect()).dialog);
  const dialog=await point('rename-dialog');
  assert.ok(dialog.b[0]>=0&&dialog.b[0]+dialog.b[2]<=480);
  await page.screenshot({path:'artifacts/material-dialog-mobile.png'});
  const mobileCanvas=await page.locator('canvas').boundingBox();
  await page.mouse.click(mobileCanvas.x+1,mobileCanvas.y+1);await wait(()=>!JSON.parse(window.gallery.inspect()).dialog);
  assert.equal((await state()).section,2,'outside dismiss must not activate the background tab');
  assert.deepEqual(errors,[]);
  const evidence={browser:await browser.version(),state:await state(),errors};
  await writeFile('artifacts/browser-material.json',JSON.stringify(evidence,null,2)+'\n');
  console.log(JSON.stringify(evidence));
}finally{await browser.close();await web.close();}
